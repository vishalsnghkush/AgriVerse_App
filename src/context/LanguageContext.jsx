export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState(() => {
    return localStorage.getItem('agriverse_mobile_lang') || 'hi';
  });

  useEffect(() => {
    localStorage.setItem('agriverse_mobile_lang', language);
  }, [language]);

  const t = (key) => {
    const langObj = TRANSLATIONS[language] || TRANSLATIONS.en;
    return langObj[key] || TRANSLATIONS.en[key] || TRANSLATIONS.hi[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, languages: LANGUAGES, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
